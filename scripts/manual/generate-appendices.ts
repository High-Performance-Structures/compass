function dataDictionary(tables: readonly TableModel[], groups: ReadonlyMap<string, readonly TableModel[]>): string {
  const out: string[] = [
    "# Appendix A. Data dictionary",
    "",
    GENERATED_NOTE,
    "",
    `The schema declares **${tables.length} tables** across ${new Set(tables.map((t) => t.schemaFile)).size} schema files (\`drizzle.config.ts\` lists them). ` +
      "Each entry gives the table's purpose (from the comment above its definition), its owning domain and the files that write it " +
      "(from `scripts/architecture-metrics.mjs`, the measure the one-writer ratchet uses), its columns and its indexes.",
    "",
    "Column flags: **PK** primary key, **U** unique, **null** nullable. A foreign key is shown as `table.column` with its `ON DELETE` action. " +
      "Allowed values are listed when the column declares a Drizzle `enum`. Dates are ISO 8601 text and money is integer cents unless a comment says otherwise.",
    "",
  ]
  for (const group of ER_GROUPS) {
    const members = groups.get(group.id) ?? []
    if (members.length === 0) continue
    out.push(`## A.${ER_GROUPS.indexOf(group) + 1} ${group.title}`, "", group.summary, "")
    for (const table of members) {
      out.push(`### ${n(table.name)}`, "")
      const curated = CURATED_PURPOSES[n(table.name)]
      out.push(
        table.purpose
          ? cell(table.purpose)
          : curated
            ? `${cell(curated)} *(Curated description; the schema has no comment yet.)*`
            : "No description in the schema file yet.",
        "",
      )
      const writers = table.writers.length
        ? table.writers.map((writer) => `\`${n(writer)}\``).join(", ")
        : "none found (read-only, written by migrations, or written outside `src/`)"
      out.push(
        `- **Schema:** \`${n(table.schemaFile)}\` (export \`${n(table.exportName)}\`)`,
        `- **Owning domain:** ${n(table.domain.startsWith("schema:") ? "not yet assigned to a domain store" : `\`src/lib/domain/${table.domain}\``)}`,
        `- **Writers (${table.writers.length}):** ${writers}`,
      )
      if (table.compositePrimaryKey) out.push(`- **Primary key:** (${table.compositePrimaryKey.join(", ")})`)
      if (table.checks > 0) out.push(`- **CHECK constraints:** ${table.checks}`)
      out.push("", "| Column | Type | Flags | Default | References | Notes |", "|---|---|---|---|---|---|")
      for (const column of table.columns) {
        const flags = [column.primaryKey ? "PK" : "", column.unique ? "U" : "", column.nullable ? "null" : ""].filter(Boolean).join(" ")
        const reference = column.references ? `${column.references}${column.onDelete ? ` (${column.onDelete})` : ""}` : ""
        const notes = [column.enumValues ? `One of: ${column.enumValues.join(", ")}.` : "", column.comment ?? ""].filter(Boolean).join(" ")
        out.push(`| ${cell(column.name)} | ${column.type} | ${flags || "—"} | ${cell(column.defaultValue)} | ${cell(reference)} | ${cell(notes)} |`)
      }
      if (table.indexes.length > 0) {
        out.push("", "| Index | Unique | Columns |", "|---|---|---|")
        for (const index of table.indexes) {
          out.push(`| ${cell(index.name)} | ${index.unique ? "yes" : "no"}${index.where ? " (partial)" : ""} | ${cell(index.columns.join(", "))} |`)
        }
      }
      out.push("")
    }
  }
  return out.join("\n")
}

function erIndex(groups: ReadonlyMap<string, readonly TableModel[]>): string {
  const out = [
    "## 5.5 Entity-relationship diagrams by domain",
    "",
    GENERATED_NOTE,
    "",
    "One diagram per domain. Each box shows a table's primary key and foreign-key columns; the full column list is in Appendix A. " +
      "Edges to `users`, `organizations` and `projects` are drawn only in their own domain's diagram, because almost every table carries `created_by`, `organization_id` or `project_id`. Rows marked `key` are primary-key columns and `ref` foreign-key columns; foreign keys to those three shared tables are left out of the boxes too. " +
      "A box with only `id` is a table from another domain that this domain points to.",
    "",
  ]
  for (const group of ER_GROUPS) {
    const members = groups.get(group.id) ?? []
    if (members.length === 0) continue
    out.push(`### ${group.title}`, "", `${group.summary} Tables (${members.length}): ${members.map((t) => `\`${n(t.name)}\``).join(", ")}.`, "")
    const chunks = diagramChunks(members)
    diagramIds(group, chunks.length).forEach((id, index) => {
      const caption = chunks.length === 1 ? group.title : `${group.title} (${index + 1} of ${chunks.length})`
      out.push(`![${caption}](diagrams/${id}.png)`, "")
    })
  }
  return out.join("\n")
}

