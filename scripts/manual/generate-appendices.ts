/** Leaves unchanged files untouched, so diagram renders stay cached. */
function writeIfChanged(path: string, content: string): void {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return
  writeFileSync(path, content)
}

async function main(): Promise<void> {
  mkdirSync(DIAGRAMS, { recursive: true })
  // ER diagrams are regenerated; stale ones are removed, hand-drawn ones kept.
  const staleEr = new Set(readdirSync(DIAGRAMS).filter((entry) => /^er-.*\.mmd$/.test(entry)))
  const tables = await buildSchemaModel(ROOT)
  const all = new Map(tables.map((table) => [table.name, table]))
  const groups = new Map<string, TableModel[]>()
  for (const table of tables) {
    const id = groupOf(table)
    groups.set(id, [...(groups.get(id) ?? []), table])
  }
  for (const group of ER_GROUPS) {
    const members = groups.get(group.id) ?? []
    if (members.length === 0) continue
    const chunks = diagramChunks(members)
    diagramIds(group, chunks.length).forEach((id, index) => {
      writeIfChanged(join(DIAGRAMS, `${id}.mmd`), erDiagram(group, chunks[index], all))
      staleEr.delete(`${id}.mmd`)
    })
  }
  for (const entry of staleEr) rmSync(join(DIAGRAMS, entry))
  writeFileSync(join(OUT, "A-data-dictionary.md"), dataDictionary(tables, groups))
  writeFileSync(join(OUT, "05b-er-diagrams.md"), erIndex(groups))
  writeFileSync(join(OUT, "B-actions-and-routes.md"), actionsAndRoutes())
  writeFileSync(join(OUT, "C-environment.md"), environment())
  writeFileSync(join(OUT, "D-glossary.md"), glossary())
  writeFileSync(join(OUT, "12b-ratchet-counts.md"), ratchetCounts(tables))
  writeFileSync(
    join(OUT, "generated-stats.json"),
    JSON.stringify(
      {
        tables: tables.length,
        groups: Object.fromEntries(ER_GROUPS.map((group) => [group.id, (groups.get(group.id) ?? []).length])),
        tablesWithoutPurpose: tables.filter((table) => !table.purpose).length,
        tablesWithoutAnyDescription: tables.filter((table) => !table.purpose && !CURATED_PURPOSES[n(table.name)]).length,
        tablesWithMultipleWriters: tables.filter((table) => table.writers.length > 1).length,
        tablesWithoutDomainStore: tables.filter((table) => table.domain.startsWith("schema:")).length,
      },
      null,
      2,
    ) + "\n",
  )
  console.log(`generated appendices for ${tables.length} tables`)
}

await main()
