// Users and organizations are referenced by nearly every table; drawing
// those edges would bury the diagrams, so only the identity diagram shows them.
const UBIQUITOUS = new Set(["users", "organizations", "projects"])
const HOME_GROUP: Readonly<Record<string, string>> = { users: "identity", organizations: "identity", projects: "projects" }

function erEntityName(name: string): string {
  return n(name).replace(/[{}]/g, "").replace(/[^A-Za-z0-9_]/g, "_")
}

function erDiagram(group: ErGroup, tables: readonly TableModel[], all: ReadonlyMap<string, TableModel>): string {
  const names = new Set(tables.map((table) => table.name))
  // Left-to-right stacks unrelated tables vertically, which fits a page.
  const lines = ["erDiagram", "  direction LR"]
  const external = new Set<string>()
  const relations: string[] = []
  for (const table of tables) {
    for (const column of table.columns) {
      if (!column.references) continue
      const target = column.references.split(".")[0]
      if (UBIQUITOUS.has(target) && HOME_GROUP[target] !== group.id) continue
      if (!all.has(target)) continue
      if (!names.has(target)) external.add(target)
      const cardinality = column.nullable ? "|o--o{" : "||--o{"
      // Unlabelled edges: the foreign-key column is listed in the box.
      relations.push(`  ${erEntityName(target)} ${cardinality} ${erEntityName(table.name)} : ""`)
    }
  }
  for (const table of tables) {
    const hiddenTarget = (column: TableModel["columns"][number]): boolean => {
      const target = column.references?.split(".")[0]
      return Boolean(target && UBIQUITOUS.has(target) && HOME_GROUP[target] !== group.id)
    }
    const keyColumns = table.columns.filter(
      (column) =>
        column.primaryKey ||
        table.compositePrimaryKey?.includes(column.name) ||
        (column.references && !hiddenTarget(column)),
    )
    lines.push(`  ${erEntityName(table.name)} {`)
    const shown = keyColumns.slice(0, 7)
    for (const column of shown) {
      const key = column.primaryKey || table.compositePrimaryKey?.includes(column.name) ? (column.references ? "PK,FK" : "PK") : "FK"
      lines.push(`    ${key === "FK" ? "ref" : "key"} ${column.name}`)
    }
    if (keyColumns.length > shown.length) lines.push(`    ref plus_${keyColumns.length - shown.length}_more`)
    if (keyColumns.length === 0) lines.push("    key id")
    lines.push("  }")
  }
  for (const target of [...external].sort()) lines.push(`  ${erEntityName(target)} {\n    key id\n  }`)
  return [...lines, ...[...new Set(relations)].sort()].join("\n") + "\n"
}

const MAX_TABLES_PER_DIAGRAM = 6

/**
 * Splits a domain into page-sized diagrams, keeping tables that reference
 * each other together where possible (connected components, largest first).
 */
function diagramChunks(tables: readonly TableModel[]): TableModel[][] {
  const names = new Set(tables.map((table) => table.name))
  const parent = new Map(tables.map((table) => [table.name, table.name]))
  const find = (name: string): string => {
    let root = name
    while (parent.get(root) !== root) root = parent.get(root) ?? root
    return root
  }
  for (const table of tables) {
    for (const column of table.columns) {
      const target = column.references?.split(".")[0]
      if (target && names.has(target) && !UBIQUITOUS.has(target)) parent.set(find(table.name), find(target))
    }
  }
  const components = new Map<string, TableModel[]>()
  for (const table of tables) {
    const root = find(table.name)
    components.set(root, [...(components.get(root) ?? []), table])
  }
  const sortedComponents = [...components.values()].sort((a, b) => b.length - a.length || a[0].name.localeCompare(b[0].name))
  const chunks: TableModel[][] = []
  for (const component of sortedComponents) {
    for (let start = 0; start < component.length; start += MAX_TABLES_PER_DIAGRAM) {
      const piece = component.slice(start, start + MAX_TABLES_PER_DIAGRAM)
      const open = chunks.find((chunk) => chunk.length + piece.length <= MAX_TABLES_PER_DIAGRAM)
      if (open) open.push(...piece)
      else chunks.push([...piece])
    }
  }
  return chunks
}

function diagramIds(group: ErGroup, chunkCount: number): string[] {
  return Array.from({ length: chunkCount }, (_, index) => (chunkCount === 1 ? `er-${group.id}` : `er-${group.id}-${index + 1}`))
}

