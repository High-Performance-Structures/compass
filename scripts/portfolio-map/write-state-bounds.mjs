// Write src/lib/portfolio-map/state-bounds.generated.ts from the built state terrain files,
// so server code (weather areas) knows each state's box without loading the map files.
//   node scripts/portfolio-map/write-state-bounds.mjs
import fs from "node:fs"
import path from "node:path"

const dir = path.join(process.cwd(), "public/maps/states")
const bounds = {
  // Colorado's map file predates the state files; its box is the state's rectangle.
  CO: { west: -109.05, east: -102.05, south: 37, north: 41 },
}
for (const file of fs.readdirSync(dir).filter((name) => name.endsWith("-terrain-v1.json")).sort()) {
  const { state, grid } = JSON.parse(fs.readFileSync(path.join(dir, file), "utf8"))
  bounds[state] = { west: grid.west, east: grid.east, south: grid.south, north: grid.north }
}
const lines = Object.keys(bounds)
  .sort()
  .map((code) => {
    const b = bounds[code]
    return `  ${code}: { west: ${b.west}, east: ${b.east}, south: ${b.south}, north: ${b.north} },`
  })
const out = `// Generated by scripts/portfolio-map/write-state-bounds.mjs from public/maps/states. Do not edit.
import type { MapStateCode } from "@/lib/portfolio-map/states"

export type StateBounds = { readonly west: number; readonly east: number; readonly south: number; readonly north: number }

export const STATE_BOUNDS: Readonly<Partial<Record<MapStateCode, StateBounds>>> = {
${lines.join("\n")}
}
`
fs.writeFileSync(path.join(process.cwd(), "src/lib/portfolio-map/state-bounds.generated.ts"), out)
console.log(`${Object.keys(bounds).length} states`)
