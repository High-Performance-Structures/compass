function exportedFunctions(text: string): string[] {
  const names = new Set<string>()
  for (const match of text.matchAll(/export\s+(?:async\s+)?function\s+([A-Za-z0-9_]+)/g)) names.add(match[1])
  for (const match of text.matchAll(/export\s+const\s+([A-Za-z0-9_]+)\s*=\s*(?:async\s*)?\(/g)) names.add(match[1])
  return [...names]
}

function contextStyle(text: string): string {
  if (/\bprojectContext\(/.test(text)) return "projectContext"
  if (/\borgContext\(/.test(text)) return "orgContext"
  if (/\b(requireUserContext|userContext)\(/.test(text)) return "userContext"
  if (/getCloudflareContext\(\)/.test(text)) return "hand-rolled"
  if (/\b(requireAuth|getCurrentUser)\(/.test(text)) return "session (auth helper)"
  return "—"
}

function routeAuth(path: string, text: string): string {
  if (/retiredSyncEndpoint/.test(text)) return "retired (always refuses)"
  if (/verifyJarvisRequest|verifyJarvisSignature/.test(text)) return "signed request (HMAC)"
  if (/verify[A-Za-z]*BridgeRequest/.test(text)) return "signed request (accounting bridge HMAC)"
  if (/validateAgentAuth/.test(text)) return "agent API key"
  if (/WEBHOOK_SECRET|WEBHOOK_SIGNATURE/.test(text)) return "provider webhook secret"
  if (path.startsWith("/api/auth/")) return "public (sign-in flow)"
  if (/webhook/i.test(path) && /signature/i.test(text)) return "provider webhook signature"
  if (/Bearer/.test(text) && /SECRET|TOKEN/.test(text)) return "bearer secret"
  if (/\b(projectContext|orgContext|userContext|requireUserContext)\(/.test(text)) return "session (action context)"
  if (/\b(requireAuth|getCurrentUser|withAuth|ensureUserExists)\(/.test(text)) return "session"
  if (/api-key|apiKey|x-api-key/i.test(text)) return "API key"
  if (/from\s+["']@\/app\/actions\//.test(text)) return "session (via server action)"
  return "public / custom (see file)"
}

function actionsAndRoutes(): string {
  const actionFiles = walk("src/app/actions", (path) => /\.ts$/.test(path) && !/\.test\.ts$/.test(path)).sort()
  const routeFiles = walk("src/app/api", (path) => /\/route\.ts$/.test(path)).sort()
  let actionCount = 0
  const actionRows: string[] = []
  for (const file of actionFiles) {
    const text = readFileSync(join(ROOT, file), "utf8")
    const names = exportedFunctions(text)
    actionCount += names.length
    actionRows.push(`| \`${n(relative("src/app/actions", file))}\` | ${contextStyle(text)} | ${names.length} | ${cell(names.map((name) => `\`${name}\``).join(", "))} |`)
  }
  const routeRows: string[] = []
  for (const file of routeFiles) {
    const text = readFileSync(join(ROOT, file), "utf8")
    const methods = [...text.matchAll(/export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|PATCH|DELETE|OPTIONS|HEAD)\b/g)].map((m) => m[1])
    const path = "/" + relative("src/app", file).replace(/\/route\.ts$/, "")
    routeRows.push(`| \`${n(path)}\` | ${[...new Set(methods)].join(", ") || "—"} | ${routeAuth(path, text)} |`)
  }
  return [
    "# Appendix B. Server actions and API routes",
    "",
    GENERATED_NOTE,
    "",
    `## B.1 Server actions (${actionFiles.length} files, ${actionCount} exported functions)`,
    "",
    "Every file in `src/app/actions/` starts with `\"use server\"`; each exported async function is callable from client components. " +
      "**Context** is how the file resolves the caller: `projectContext`, `orgContext` or `userContext` from `src/lib/server/action-context.ts` (the standard), " +
      "`hand-rolled` where the file still calls `getCloudflareContext()` itself (tracked by the `handRolledContext` ratchet), or an older auth helper.",
    "",
    "| File | Context | Count | Exported functions |",
    "|---|---|---|---|",
    ...actionRows,
    "",
    `## B.2 API routes (${routeFiles.length})`,
    "",
    "Route handlers under `src/app/api/`. **Auth** is inferred from the code: `signed request (HMAC)` routes verify `X-Compass-Timestamp` / `X-Compass-Signature` " +
      "with the bridge secret (scheduled jobs and on-premises agents use these); `provider webhook signature` routes verify the provider's own signature header; " +
      "`session` routes require a signed-in user. Treat `public / custom` as \"read the file\": some are intentionally public (sign-in, public quote and order pages, health).",
    "",
    "| Route | Methods | Auth |",
    "|---|---|---|",
    ...routeRows,
    "",
  ].join("\n")
}

