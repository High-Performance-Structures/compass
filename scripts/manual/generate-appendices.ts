const n = (text: string | null | undefined): string => neutralize(text ?? "") ?? ""
const cell = (text: string | null | undefined): string =>
  n(text).replace(/\|/g, "\\|").replace(/\n/g, " ").trim() || "—"

function walk(dir: string, accept: (path: string) => boolean): string[] {
  const absolute = join(ROOT, dir)
  if (!existsSync(absolute)) return []
  return readdirSync(absolute).flatMap((entry) => {
    if (entry === "node_modules" || entry === "__tests__") return []
    const path = join(dir, entry)
    return statSync(join(ROOT, path)).isDirectory() ? walk(path, accept) : accept(path) ? [path] : []
  })
}

